from abc import ABC, abstractmethod
from typing import Dict, Any, List

class OutputAdapter(ABC):
    """
    Abstract base class to adapt mock_court outputs to J1Bench evaluator inputs.
    """
    
    @abstractmethod
    def adapt(self, raw_output: Dict[str, Any]) -> Dict[str, Any]:
        """Convert a raw output record to evaluator-ready format."""
        pass

class CDOutputAdapter(OutputAdapter):
    def adapt(self, raw_output: Dict[str, Any]) -> Dict[str, Any]:
        """
        Adapt CD (Complaint) output.
        Assuming 'raw_output' comes from CD_prediction.jsonl generated by mock_court.
        Expected structure for Evaluator likely needs parsed fields or the raw text to be parsed again.
        Since J1Bench CDEvaluator has a .reformat() method, we might just need to pass the raw generated document text.
        """
        # mock_court_multiagents output structure (inferred):
        # {
        #   "id": "CD-1",
        #   "dialog_history": [...],
        #   "generated_doc": "..." # Full text of the complaint
        # }
        
        return {
            "id": raw_output.get("id"),
            "dialog_history": raw_output.get("dialog_history", []),
            "model_output": raw_output.get("generated_doc", "")
            # Evaluator will likely take model_output and parse it itself
        }

class DDOutputAdapter(OutputAdapter):
    def adapt(self, raw_output: Dict[str, Any]) -> Dict[str, Any]:
        return {
            "id": raw_output.get("id"),
            "dialog_history": raw_output.get("dialog_history", []),
            "model_output": raw_output.get("generated_doc", "")
        }

